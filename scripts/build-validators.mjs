// Compile the vendored schemas into standalone validator code at build time,
// so the plugin never compiles schemas (or calls `new Function`) at runtime.
// Output is generated, gitignored, and rebuilt by `npm run build` / `npm test`.
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const load = (p) => JSON.parse(readFileSync(new URL(`../schemas/${p}`, import.meta.url), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
for (const p of [
  "definitions/entity-reference.schema.json",
  "document-reference.schema.json",
  "citation.schema.json",
  "container.schema.json",
  "relationship-types-config.schema.json",
  "mif.schema.json",
]) ajv.addSchema(load(p));

const exportsMap = {
  validateMif: "https://mif-spec.dev/schema/mif.schema.json",
  validateConfig: "https://mif-spec.dev/schema/relationship-types-config.schema.json",
};
const RUNTIME = {
  "ajv-formats/dist/formats": "formats",
  "ajv/dist/runtime/ucs2length": "ucs2",
};
let source = standaloneCode(ajv, exportsMap).replace(/require\("([^"]+)"\)/g, (_, spec) => {
  if (!(spec in RUNTIME)) throw new Error(`unmapped runtime require: ${spec}`);
  return `__runtime.${RUNTIME[spec]}`;
});
source = `import * as __runtime from "../validator-runtime";\n${source}`;
const outDir = new URL("../src/engine/generated/", import.meta.url);
mkdirSync(outDir, { recursive: true });
writeFileSync(new URL("validators.js", outDir), `// GENERATED by scripts/build-validators.mjs — do not edit.\n${source}`);
writeFileSync(new URL("validators.d.ts", outDir), `// GENERATED by scripts/build-validators.mjs — do not edit.
import type { ErrorObject } from "ajv";
interface Validator { (data: unknown): boolean; errors?: ErrorObject[] | null }
${Object.keys(exportsMap).map((k) => `export declare const ${k}: Validator;`).join("\n")}
`);
console.log(`generated ${Object.keys(exportsMap).length} validators (${(source.length / 1024).toFixed(0)} KiB)`);
